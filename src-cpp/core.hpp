inline constexpr double PI = 3.141592653589793;
inline double clamp(double v) { return v < 0 ? 0 : v > 1 ? 1 : v; }
inline double smooth(double a, double b, double v) {
    const double k = clamp((v - a) / (b - a));
    return k * k * (3 - 2 * k);
}
inline double mix(double a, double b, double k) { return a + (b - a) * k; }
inline double sq(double x) { return x * x; }
inline int jsround(double x) { return int(std::floor(x + 0.5)); }
using Floats = std::vector<float>;
// Preserve the original Float32 storage / double arithmetic behavior.
inline double get(const Floats &a, int i) { return double(a[i]); }

struct Piece {
    std::u16string text;
    std::vector<uint8_t> colors;
    virtual ~Piece() = default;
    virtual void frame(double t, bool paper, bool colored) = 0;

    void join(const std::vector<char16_t> &chars, int w, int h) {
        text.clear();
        text.reserve(w * h + h - 1);
        for (int r = 0; r < h; ++r) {
            if (r) text.push_back(u'\n');
            text.append(chars.data() + r * w, w);
        }
    }
};

